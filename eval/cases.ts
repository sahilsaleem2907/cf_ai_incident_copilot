/**
 * LLM eval cases and scoring (TDD §16, PRD §11.4). Pure and import-free: `eval/run.ts` runs under Node's
 * type stripping, so this file holds only erasable TypeScript, and the unit tests import it as is.
 */

/** Copied from `worker/llm/models.ts` (eval can't import worker code); results.md names them. */
export const MODELS = { primary: "@cf/openai/gpt-oss-120b", fallback: "@cf/zai-org/glm-4.7-flash" } as const;
export const QUESTION = "what's wrong with my demo service?";
/** At least 4 of 5 cases must pass. */
export const TARGET_PASSES = 4;

export type EvalCase = { mode: string; expected: string };
export const CASES: readonly EvalCase[] = [
  { mode: "slow", expected: "high_latency" },
  { mode: "errors", expected: "origin_5xx" },
  { mode: "redirect_loop", expected: "redirect_loop" },
  { mode: "bad_cache", expected: "cache_misconfiguration" },
  { mode: "healthy", expected: "healthy" },
];

/** The parts of `IncidentState` (worker/agent/state.ts) the eval reads from `GET /api/incidents/:id`. */
export type Snapshot = {
  status: string;
  category: string | null;
  confidence: string | null;
  mode: string;
  activeRunId: string | null;
  findings: { category: string; evidence: string[]; actions: string[]; cause: string } | null;
  checks: { evidenceId: string; status: string }[];
  approvals: { actionId: string; status: string }[];
  timeline: { type: string; detail: Record<string, string | number | boolean | null> }[];
};

export type Score = {
  mode: string;
  expected: string;
  got: string | null;
  confidence: string | null;
  /** ① category, ② cites a finished `http-*` check, ③ restore proposed (not proposed for healthy). */
  category: boolean;
  citation: boolean;
  action: boolean;
  /** `ai`, or `rule_based` when the LLM was never used (a failure: the eval measures the AI). */
  runMode: string;
  /** `run_finished` details (WP-20): who made the findings, turns the fallback model answered, why the run ended. */
  source: string | null;
  fallbackTurns: number | null;
  runStatus: string | null;
  seconds: number;
  pass: boolean;
  reasons: string[];
};

const RESTORE = "restore_demo_service";

export function score(c: EvalCase, s: Snapshot, seconds: number): Score {
  const reasons: string[] = [];
  const finished = new Set(s.checks.filter((k) => k.status !== "pending" && k.status !== "running" && k.status !== "unavailable").map((k) => k.evidenceId));
  const evidence = s.findings?.evidence ?? [];
  const restore = s.approvals.some((a) => a.actionId === RESTORE) || (s.findings?.actions ?? []).includes(RESTORE);
  const end = [...s.timeline].reverse().find((t) => t.type === "run_finished")?.detail ?? {};

  const category = s.category === c.expected;
  if (!category) reasons.push(`category ${s.category ?? "none"}, expected ${c.expected}`);
  const citation = evidence.some((id) => /^http-\d+$/.test(id) && finished.has(id));
  if (!citation) reasons.push(`no finished http-* check cited (evidence: ${evidence.join(", ") || "none"})`);
  const healthy = c.expected === "healthy";
  const action = healthy ? !restore : s.approvals.some((a) => a.actionId === RESTORE);
  if (!action) reasons.push(healthy ? "restore_demo_service proposed for a healthy demo" : "restore_demo_service not proposed");
  if (s.mode !== "ai") reasons.push("fell back to rules: the LLM was not used");

  return {
    mode: c.mode,
    expected: c.expected,
    got: s.category,
    confidence: s.confidence,
    category,
    citation,
    action,
    runMode: s.mode,
    source: typeof end.source === "string" ? end.source : null,
    fallbackTurns: typeof end.fallbackTurns === "number" ? end.fallbackTurns : null,
    runStatus: typeof end.status === "string" ? end.status : null,
    seconds,
    pass: category && citation && action && s.mode === "ai",
    reasons,
  };
}

/** A case that never produced a snapshot (a refused request, a run that didn't finish). */
export function failed(c: EvalCase, reason: string, seconds: number): Score {
  return {
    mode: c.mode,
    expected: c.expected,
    got: null,
    confidence: null,
    category: false,
    citation: false,
    action: false,
    runMode: "-",
    source: null,
    fallbackTurns: null,
    runStatus: null,
    seconds,
    pass: false,
    reasons: [reason],
  };
}

const mark = (ok: boolean) => (ok ? "✓" : "✗");

export function renderResults(rows: Score[], meta: { date: string; target: string }): string {
  const passes = rows.filter((r) => r.pass).length;
  const lines = [
    "# LLM eval results",
    "",
    `Generated by \`pnpm eval\` (TDD §16). Each case sets the demo service to a mode, asks "${QUESTION}", waits for the diagnosis run to finish, and scores the incident snapshot.`,
    "",
    `- **Date:** ${meta.date}`,
    `- **Target:** ${meta.target}`,
    `- **Models:** ${MODELS.primary} (primary), ${MODELS.fallback} (fallback)`,
    `- **Result:** ${passes}/${rows.length} passed (target ≥ ${TARGET_PASSES}/${CASES.length}): **${passes >= TARGET_PASSES ? "met" : "not met"}**`,
    "",
    "Checks: ① the category is right, ② the findings cite a finished `http-*` check, ③ `restore_demo_service` is proposed (for `healthy`: not proposed). A run that never used the LLM (`rule_based`) fails. *Findings* is who made them: `model` (a valid `submit_findings`), `model+rules` (the rules kept the valid fields of an invalid call) or `rules`.",
    "",
    "| Demo mode | Expected | Got | Confidence | ① | ② | ③ | Findings | Fallback turns | Run | Time | Pass |",
    "|---|---|---|---|---|---|---|---|---|---|---|---|",
    ...rows.map(
      (r) =>
        `| \`${r.mode}\` | \`${r.expected}\` | ${r.got ? `\`${r.got}\`` : "–"} | ${r.confidence ?? "–"} | ${mark(r.category)} | ${mark(r.citation)} | ${mark(r.action)} | ${r.runMode === "ai" ? (r.source ?? "?") : r.runMode} | ${r.fallbackTurns ?? "–"} | ${r.runStatus ?? "–"} | ${r.seconds} s | ${r.pass ? "**pass**" : "fail"} |`,
    ),
  ];
  const failures = rows.filter((r) => r.reasons.length);
  if (failures.length) lines.push("", "## Notes", "", ...failures.map((r) => `- \`${r.mode}\`: ${r.reasons.join("; ")}`));
  return lines.join("\n") + "\n";
}
